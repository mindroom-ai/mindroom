@dataclass(frozen=True)
class _LegacyDatabase:
    execute: Callable[[str], None]
    query: Callable[[str], list[tuple[object, ...]]]
    open: Callable[[], EventJournalStore]
    postgres: bool


@pytest.fixture(params=("sqlite", "postgres"))
def legacy_database(request: pytest.FixtureRequest, tmp_path: Path) -> Iterator[_LegacyDatabase]:
    """Create actual released DDL before any current backend opens it."""
    schema = _SCHEMA.read_text()
    if request.param == "sqlite":
        path = tmp_path / "legacy.db"

        def execute(sql: str) -> None:
            with closing(sqlite3.connect(path)) as connection:
                connection.executescript(sql)

        def query(sql: str) -> list[tuple[object, ...]]:
            with closing(sqlite3.connect(path)) as connection:
                return connection.execute(sql).fetchall()

        def opener() -> EventJournalStore:
            return EventJournalStore.open_sqlite(path)
    else:
        url = postgres_journal_schema_url(request.getfixturevalue("postgres_journal_url"))
        schema = schema.replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )

        def execute(sql: str) -> None:
            with psycopg.connect(url) as connection:
                connection.execute(cast("LiteralString", sql))

        def query(sql: str) -> list[tuple[object, ...]]:
            with psycopg.connect(url) as connection:
                return connection.execute(cast("LiteralString", sql)).fetchall()

        def opener() -> EventJournalStore:
            return EventJournalStore.open_postgres(url)

    execute(schema)
    execute("INSERT INTO journal_identity VALUES (TRUE, 'original-journal-generation')")
    return _LegacyDatabase(execute, query, opener, request.param == "postgres")


@pytest.mark.asyncio
async def test_released_journal_upgrades_and_preserves_new_work(legacy_database: _LegacyDatabase) -> None:
    """Upgrade preserves identity/history, abandons pending work, and runs only once."""
    legacy_database.execute(_OLD_EVENT)
    legacy_database.execute("""
        INSERT INTO visible_messages VALUES (
            '@bot:example.org', '!room:example.org', '$old', '', '@user:example.org', 1,
            '$old', 1, '{"body":"Old request","msgtype":"m.text"}', NULL, 7);
        INSERT INTO room_membership VALUES ('@bot:example.org', '!room:example.org', 7, 0, 2);
        INSERT INTO matrix_delivery_outbox (
            principal_id, delivery_id, stage, event_type, room_id, membership_epoch, thread_id,
            transaction_id, payload_json, attempted, sending_device_id, created_at_ns
        ) VALUES ('@bot:example.org', '$old', 'initial', 'm.room.message', '!room:example.org', 7,
                  '', 'old-transaction', '{}', 1, 'OLD_DEVICE', 1);
        INSERT INTO approval_continuations (
            principal_id, approval_id, entity_name, state, context_json, created_at_ns
        ) VALUES ('@bot:example.org', 'old-approval', 'bot', 'claimed', '{}', 1);
        INSERT INTO approval_continuation_sources VALUES ('@bot:example.org', 'old-approval', '$old', 0);
        INSERT INTO turn_records VALUES (
            'bot', '$completed', '$completed',
            '{"anchor_event_id":"$completed","source_event_ids":["$completed"],"completed":true,"response_event_id":"$response","timestamp":1}'
        );
    """)
    store = legacy_database.open()
    try:
        assert await store.existing_generation() == "original-journal-generation"
        principal = store.principal(_ACCOUNT)
        assert not await principal.pending()
        assert await principal.approval_continuation("old-approval") is None
        assert await store.backend.read(lambda tx: tx.fetchall("SELECT * FROM matrix_delivery_outbox")) == ()
        history = await store.backend.read(lambda tx: tx.fetchone("SELECT content_json FROM visible_messages"))
        assert history is not None
        assert "Old request" in history["content_json"]
        assert await store.backend.read(lambda tx: tx.fetchone("SELECT record_json FROM turn_records")) is not None
        consumer = await principal.load_or_create_ingestion_consumer(new_generation=uuid4())
        stream = uuid4()
        await principal.bind_ingestion_stream(generation=consumer.generation, stream_id=stream)
        await admit(principal, "$new")
    finally:
        await store.close()

    reopened = legacy_database.open()
    try:
        principal = reopened.principal(_ACCOUNT)
        assert [event.event_id for event in await principal.pending()] == ["$new"]
        restored = await principal.load_or_create_ingestion_consumer(new_generation=uuid4())
        assert restored.generation == consumer.generation
        assert restored.stream_id == stream
        assert await reopened.existing_generation() == "original-journal-generation"
    finally:
        await reopened.close()


@pytest.mark.asyncio
@pytest.mark.parametrize("old_epoch", [0, 7])
async def test_upgrade_preserves_pending_history_repair(legacy_database: _LegacyDatabase, old_epoch: int) -> None:
    """An unresolved historical body stays repairable after membership is rebased."""
    legacy_database.execute(_OLD_EVENT)
    legacy_database.execute(f"""
        INSERT INTO visible_messages VALUES (
            '@bot:example.org', '!room:example.org', '$old', '', '@user:example.org', 1,
            '$old', 1, NULL, 37, {old_epoch});
    """)  # noqa: S608 -- epoch is a fixed test parameter
    store = legacy_database.open()
    try:
        page = await store.principal(_ACCOUNT).read_conversation(room_id="!room:example.org", thread_id=None, limit=10)
        assert not page.messages
        (repair,) = page.refresh_pending
        assert repair.membership_epoch == 0
    finally:
        await store.close()

    reopened = legacy_database.open()
    try:
        principal = reopened.principal(_ACCOUNT)
        assert await principal.install_refetched_revision(
            repair,
            revision_event_id="$old",
            revision_ts=1,
            revision_sender="@user:example.org",
            content={"body": "Recovered historical body", "msgtype": "m.text"},
        )
        page = await principal.read_conversation(room_id="!room:example.org", thread_id=None, limit=10)
        assert not page.refresh_pending
        assert [message.content["body"] for message in page.messages] == ["Recovered historical body"]
        assert not await principal.pending()
    finally:
        await reopened.close()


@pytest.mark.asyncio
@pytest.mark.parametrize("old_state", ["pending", "settled"])
@pytest.mark.parametrize("event_class", [EventClass.CONTEXT_ONLY, EventClass.ACTIONABLE])
async def test_upgrade_keeps_late_decrypted_history_silent(
    legacy_database: _LegacyDatabase,
    old_state: str,
    event_class: EventClass,
) -> None:
    """Old unreadable identities accept later plaintext without owning a new turn."""
    legacy_database.execute(
        _OLD_EVENT.replace("'message'", "'decryption_failure'").replace("'pending'", f"'{old_state}'"),
    )
    stream = uuid4()
    for sequence in (1, 2):
        store = legacy_database.open()
        try:
            principal = store.principal(_ACCOUNT)
            old = await principal.load_event("$old")
            assert old is not None
            assert old.kind is EventKind.OPAQUE_HISTORY
            consumer = await principal.load_or_create_ingestion_consumer(new_generation=uuid4())
            await principal.bind_ingestion_stream(generation=consumer.generation, stream_id=stream)
            event, projected = message(
                "$old",
                room_id="!room:example.org",
                sender="@user:example.org",
                ts=1,
                event_class=event_class,
                content={"body": "Decrypted old text", "msgtype": "m.text"},
            )
            facts = await principal.admit_ingestion_batch(
                IngestionBatchAdmission(
                    stream,
                    sequence,
                    (
                        IngestionRecordAdmission(
                            IngestionRecordDisposition.SEMANTIC_EVENT,
                            event=event,
                            projected=projected,
                        ),
                    ),
                ),
            )
            assert not facts.semantic_event_new
            assert not await principal.pending()
            page = await principal.read_conversation(room_id="!room:example.org", thread_id=None, limit=10)
            assert [item.content["body"] for item in page.messages] == ["Decrypted old text"]
        finally:
            await store.close()


