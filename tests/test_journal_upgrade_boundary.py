@pytest.mark.asyncio
async def test_interrupted_upgrade_rolls_back_and_retries(legacy_database: _LegacyDatabase) -> None:
    """Failed DDL cannot publish the new marker while abandoning only part of old work."""
    legacy_database.execute(_OLD_EVENT)
    module = postgres_backend if legacy_database.postgres else sqlite_backend
    original = module.schema_statements
    with (
        patch.object(
            module,
            "schema_statements",
            side_effect=lambda dialect: (*original(dialect), "INVALID UPGRADE SQL"),
        ),
        pytest.raises((sqlite3.OperationalError, psycopg.errors.SyntaxError)),
    ):
        legacy_database.open()
    assert legacy_database.query("SELECT state, membership_epoch FROM journal_events") == [("pending", 7)]
    assert legacy_database.query("SELECT generation FROM journal_identity") == [("original-journal-generation",)]
    marker_query = (
        "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema() "
        "AND table_name = 'matrix_sync_consumers'"
        if legacy_database.postgres
        else "SELECT name FROM sqlite_master WHERE name = 'matrix_sync_consumers'"
    )
    assert legacy_database.query(marker_query) == []
    store = legacy_database.open()
    try:
        assert not await store.principal(_ACCOUNT).pending()
    finally:
        await store.close()


@pytest.mark.asyncio
async def test_concurrent_startups_share_one_upgrade(legacy_database: _LegacyDatabase) -> None:
    """Competing schema openers preserve one generation and one consumer binding."""
    legacy_database.execute(_OLD_EVENT)
    first, second = await asyncio.gather(*(asyncio.to_thread(legacy_database.open) for _ in range(2)))
    try:
        consumers = await asyncio.gather(
            first.principal(_ACCOUNT).load_or_create_ingestion_consumer(new_generation=uuid4()),
            second.principal(_ACCOUNT).load_or_create_ingestion_consumer(new_generation=uuid4()),
        )
        assert consumers[0] == consumers[1]
        assert not await first.principal(_ACCOUNT).pending()
        assert await second.existing_generation() == "original-journal-generation"
    finally:
        await first.close()
        await second.close()


