@pytest.mark.parametrize("call", _TRANSCRIPT_CALLS)
@pytest.mark.parametrize(
    ("status", "graph_code", "inner_code", "code", "phrase"),
    [
        (403, "Forbidden", "GraphAccessToTranscriptsDisabled", "transcripts_disabled", "administrator"),
        (403, "Forbidden", None, "forbidden", "calendar invite"),
        (404, "NotFound", None, "not_found", "expired"),
        (412, "PreconditionFailed", None, "no_calendar_event", "calendar event"),
    ],
)
def test_transcript_refusals_explain_their_cause(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    call: Callable[[MicrosoftMeetingsTools], str],
    status: int,
    graph_code: str,
    inner_code: str | None,
    code: str,
    phrase: str,
) -> None:
    tools, _graph = _tools(tmp_path, monkeypatch, _refusal(status, graph_code, inner_code))

    result = _payload(call(tools))

    assert (result["status"], result["code"], result["graph_code"]) == ("error", code, graph_code)
    assert phrase in result["message"]
    assert "Graph says no." not in result["message"]
    assert result["graph_message"] == "Graph says no."


