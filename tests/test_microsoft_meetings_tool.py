def _answer(payload: dict[str, object], status: int = 200) -> Callable[[httpx.Request], httpx.Response]:
    return lambda _request: httpx.Response(status, json=payload)


def _vtt(content: str) -> Callable[[httpx.Request], httpx.Response]:
    return lambda _request: httpx.Response(200, content=content.encode("utf-8"), headers={"Content-Type": "text/vtt"})


def _refusal(status: int, code: str, inner_code: str | None = None) -> Callable[[httpx.Request], httpx.Response]:
    error: dict[str, object] = {"code": code, "message": "Graph says no."}
    if inner_code is not None:
        error["innerError"] = {"code": inner_code}
    return _answer({"error": error}, status=status)


def _tools(
    tmp_path: Path,
    monkeypatch: pytest.MonkeyPatch,
    handler: Callable[[httpx.Request], httpx.Response],
) -> tuple[MicrosoftMeetingsTools, FakeGraph]:
    graph = FakeGraph(handler).install(monkeypatch)
    paths = runtime_paths(tmp_path)
    manager = save_client_config(paths)
    publish_grant(microsoft_meetings_oauth_provider(), manager)
    tools = MicrosoftMeetingsTools(
        runtime_paths=paths,
        credentials_manager=manager,
        worker_target=worker_target(),
        runtime_config=None,
    )
    return tools, graph


def _payload(result: str) -> dict[str, Any]:
    return json.loads(result)


def _description(tools: MicrosoftMeetingsTools, name: str) -> str:
    """Return the description the model sees; deferred toolkits do not show toolkit instructions."""
    return " ".join(Function.from_callable(getattr(tools, name)).to_dict()["description"].split())


