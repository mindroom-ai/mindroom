@pytest.mark.asyncio
async def test_a_scheduled_approval_still_arms_and_claims(recorded_journal: Callable[[str], _Journal]) -> None:
    """An approval given before the upgrade arms when its task fires and is spent by one claim with its receipt."""
    store = recorded_journal("12_scheduled_calls.sql").open()
    try:
        router = store.principal(_ROUTER)
        call = await router.approvals.scheduled_call(task_id="task-approved")
        assert call is not None
        assert call.approved_scope == "any_arguments"
        digest = "4c33f7f8832d7dc5702b1348e727a1e4e2dbcef16d0122dfa1ab88015be4a3af"
        fired_at = call.execute_at_ns
        armed = await store.backend.write(
            lambda transaction: scheduled_approvals.arm(
                transaction,
                _ROUTER,
                task_id="task-approved",
                workflow_digest=digest,
                any_arguments_allowed=False,
                now_ns=fired_at,
            ),
        )
        assert armed == "armed"
        narrowed = await router.approvals.scheduled_call(task_id="task-approved")
        assert narrowed is not None
        assert narrowed.approved_scope == "exact_arguments"
        receipt = ApprovalCardReservation(
            delivery_id="scheduled-receipt:task-approved",
            tool_call_id="task-approved",
            event_type="io.mindroom.tool_approval",
            payload={"approval_id": "scheduled-receipt:task-approved", "tool_name": call.tool_name},
            approver_user_id=_ALICE,
            approvable=False,
        )
        claimed = await store.backend.write(
            lambda transaction: scheduled_approvals.claim(
                transaction,
                _ROUTER,
                call=narrowed,
                arguments_json=call.arguments_json,
                receipt=receipt,
                now_ns=fired_at,
            ),
        )
        assert isinstance(claimed, ScheduledCallClaim)
        assert claimed.provenance["approved_by"] == _ALICE
        assert claimed.provenance["approval_card_event_id"] == "$scheduled-approval:task-approved"
        assert claimed.provenance["scope"] == "exact_arguments"
        again = await store.backend.write(
            lambda transaction: scheduled_approvals.claim(
                transaction,
                _ROUTER,
                call=narrowed,
                arguments_json=call.arguments_json,
                receipt=receipt,
                now_ns=fired_at,
            ),
        )
        assert again == "used"
        armed = await router.approvals.scheduled_call(task_id="task-armed")
        assert armed is not None
        armed_claim = await store.backend.write(
            lambda transaction: scheduled_approvals.claim(
                transaction,
                _ROUTER,
                call=armed,
                arguments_json=armed.arguments_json,
                receipt=replace(receipt, delivery_id="scheduled-receipt:task-armed", tool_call_id="task-armed"),
                now_ns=armed.execute_at_ns,
            ),
        )
        assert isinstance(armed_claim, ScheduledCallClaim)
        # Armed before the upgrade, it is spent under the scope it was armed for.
        assert armed_claim.provenance["scope"] == "exact_arguments"
        withdrawn = await router.approvals.scheduled_call(task_id="task-withdrawn")
        assert withdrawn is not None
        assert (
            await router.approvals.approval_card(room_id=_ROOM, card_event_id="$scheduled-receipt:task-consumed")
            is not None
        )
        [pending] = await router.approvals.pending_approval_cards(room_id=_ROOM)
        # Its card offered only the stored arguments.
        assert (pending.owner_kind, pending.any_arguments_offered) == ("scheduled", False)
    finally:
        await store.close()


