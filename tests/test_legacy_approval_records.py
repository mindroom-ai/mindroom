@dataclass(frozen=True)
class _Journal:
    query: Callable[[str], list[tuple[object, ...]]]
    tables: Callable[[], frozenset[str]]
    open: Callable[[], EventJournalStore]


def _legacy(recording: str) -> sqlite3.Connection:
    """Load one recording into an in-memory journal of the schema it was recorded under."""
    connection = sqlite3.connect(":memory:")
    connection.executescript((_FIXTURES / "schema.sql").read_text())
    connection.executescript((_FIXTURES / recording).read_text())
    return connection


def _copy_to_postgres(legacy: sqlite3.Connection, url: str) -> None:
    """Create the recorded schema on PostgreSQL and copy every recorded row into it, in creation order."""
    schema = (
        (_FIXTURES / "schema.sql")
        .read_text()
        .replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
        )
    )
    tables = [
        str(row[0])
        for row in legacy.execute("SELECT name FROM sqlite_master WHERE type = 'table' AND name <> 'sqlite_sequence'")
    ]
    with psycopg.connect(url) as connection:
        connection.execute(cast("LiteralString", schema))
        for table in tables:
            booleans = {
                str(row[0])
                for row in connection.execute(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s AND data_type = 'boolean'",
                    (table,),
                )
            }
            cursor = legacy.execute(f"SELECT * FROM {table}")  # noqa: S608 - recorded table names
            columns = [str(column[0]) for column in cursor.description]
            insert = f"INSERT INTO {table} ({', '.join(columns)}) VALUES ({', '.join('%s' for _ in columns)})"  # noqa: S608
            for row in cursor.fetchall():
                connection.execute(
                    cast("LiteralString", insert),
                    [
                        bool(value) if column in booleans and value is not None else value
                        for column, value in zip(columns, row, strict=True)
                    ],
                )
        connection.execute(
            "SELECT setval(pg_get_serial_sequence('journal_events', 'receipt_order'), "
            "COALESCE((SELECT MAX(receipt_order) FROM journal_events), 0) + 1, false)",
        )


@pytest.fixture(params=("sqlite", "postgres"))
def recorded_journal(request: pytest.FixtureRequest, tmp_path: Path) -> Callable[[str], _Journal]:
    """Return a loader that puts one recording into a fresh database of this backend."""

    def load(recording: str) -> _Journal:
        with closing(_legacy(recording)) as legacy:
            if request.param == "sqlite":
                path = tmp_path / "journal.db"
                with closing(sqlite3.connect(path)) as target:
                    legacy.backup(target)
            else:
                url = postgres_journal_schema_url(request.getfixturevalue("postgres_journal_url"))
                _copy_to_postgres(legacy, url)
        if request.param == "sqlite":

            def query(sql: str) -> list[tuple[object, ...]]:
                with closing(sqlite3.connect(path)) as connection:
                    return connection.execute(sql).fetchall()

            return _Journal(
                query,
                lambda: frozenset(str(row[0]) for row in query("SELECT name FROM sqlite_master WHERE type = 'table'")),
                lambda: EventJournalStore.open_sqlite(path),
            )

        def postgres_query(sql: str) -> list[tuple[object, ...]]:
            with psycopg.connect(url) as connection:
                return connection.execute(cast("LiteralString", sql)).fetchall()

        return _Journal(
            postgres_query,
            lambda: frozenset(
                str(row[0])
                for row in postgres_query(
                    "SELECT table_name FROM information_schema.tables WHERE table_schema = current_schema()",
                )
            ),
            lambda: EventJournalStore.open_postgres(url),
        )

    return load


def _snapshot(journal: _Journal) -> dict[str, list[str]]:
    return {table: sorted(map(repr, journal.query(f"SELECT * FROM {table}"))) for table in _CURRENT_TABLES}  # noqa: S608


def _known_card_events(recording: str) -> set[tuple[str, str, str]]:
    """Return every event the earlier release recognized as showing a card: tombstones and acknowledged cards."""
    with closing(_legacy(recording)) as legacy:
        return {
            (str(row[0]), str(row[1]), str(row[2]))
            for row in legacy.execute(
                """
                SELECT principal_id, room_id, card_event_id FROM approval_action_tombstones
                UNION
                SELECT initial.principal_id, initial.room_id, initial.acknowledged_event_id
                FROM approval_cards AS cards
                JOIN matrix_delivery_outbox AS initial
                  ON initial.principal_id = cards.principal_id AND initial.delivery_id = cards.delivery_id
                 AND initial.stage = 'initial'
                WHERE initial.acknowledged_event_id IS NOT NULL
                """,
            )
        }


@pytest.mark.asyncio
@pytest.mark.parametrize("recording", _RECORDINGS)
async def test_every_recording_converts_to_consistent_rows_once(
    recorded_journal: Callable[[str], _Journal],
    recording: str,
) -> None:
    """No legacy table survives, every live card keeps its delivery and call, every known event finds its card."""
    journal = recorded_journal(recording)
    store = journal.open()
    try:
        tables = journal.tables()
        assert tables.isdisjoint(_LEGACY_TABLES)
        assert set(_CURRENT_TABLES) <= tables
        assert (
            journal.query(
                """
                SELECT cards.delivery_id FROM approval_cards AS cards
                LEFT JOIN matrix_delivery_outbox AS initial
                  ON initial.principal_id = cards.principal_id AND initial.delivery_id = cards.delivery_id
                 AND initial.stage = 'initial'
                LEFT JOIN approval_calls AS calls
                  ON calls.owner_id = cards.owner_id AND calls.generation = cards.generation
                 AND calls.tool_call_id = cards.tool_call_id
                WHERE cards.retired = 0 AND (initial.delivery_id IS NULL OR calls.owner_id IS NULL)
                """,
            )
            == []
        )
        assert (
            journal.query(
                """
                SELECT events.card_event_id FROM approval_card_events AS events
                LEFT JOIN approval_cards AS cards
                  ON cards.principal_id = events.principal_id AND cards.delivery_id = events.delivery_id
                WHERE cards.delivery_id IS NULL
                """,
            )
            == []
        )
        # A tombstone's placeholder card exists only for the event no converted card showed.
        assert (
            journal.query(
                """
                SELECT cards.delivery_id FROM approval_cards AS cards
                LEFT JOIN approval_card_events AS events
                  ON events.principal_id = cards.principal_id AND events.delivery_id = cards.delivery_id
                WHERE cards.delivery_id LIKE 'legacy-tombstone:%' AND events.card_event_id IS NULL
                """,
            )
            == []
        )
        for principal_id, room_id, card_event_id in _known_card_events(recording):
            card = await store.principal(principal_id).approvals.approval_card(
                room_id=room_id,
                card_event_id=card_event_id,
            )
            assert card is not None, card_event_id
    finally:
        await store.close()
    converted = _snapshot(journal)
    await journal.open().close()
    assert _snapshot(journal) == converted


