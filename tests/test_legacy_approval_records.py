@pytest.mark.asyncio
async def test_a_receipt_outliving_its_reply_keeps_its_granted_call_until_it_retires(
    recorded_journal: Callable[[str], _Journal],
) -> None:
    """A live receipt whose paused reply finished gets its granted call back, which goes once the receipt retires."""
    journal = recorded_journal("16_receipt_after_reply_ended.sql")
    store = journal.open()
    try:
        router = store.principal(_ROUTER)
        receipt = await router.approvals.approval_card(room_id=_ROOM, card_event_id="$receipt-live-0-0")
        assert isinstance(receipt, ApprovalCardView)
        assert (receipt.kind, receipt.retired) == ("grant_receipt", False)
        assert journal.query(
            "SELECT decision, grant_id, tool_name FROM approval_calls WHERE owner_id = 'receipt-live'",
        ) == [("approved", "00000000-0000-0000-0000-00000000000c", "run_shell_command")]
        await router.approvals.maintain_automatic_approvals()
        assert journal.query("SELECT owner_id FROM approval_calls WHERE owner_id = 'receipt-live'") == []
        retired = await router.approvals.approval_card(room_id=_ROOM, card_event_id="$receipt-live-0-0")
        assert isinstance(retired, ApprovalCardView)
        assert retired.retired
    finally:
        await store.close()
