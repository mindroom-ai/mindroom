_RECORDINGS = Path(__file__).parent / "fixtures" / "approval_records"
_RESPONDER = "code@@mindroom_code:example.org"


def _load_sqlite(path: Path) -> None:
    """Load the schema and the failing paused replies a release before the conversion recorded."""
    with closing(sqlite3.connect(path)) as connection:
        connection.executescript((_RECORDINGS / "schema.sql").read_text(encoding="utf-8"))
        connection.executescript((_RECORDINGS / "06_failing.sql").read_text(encoding="utf-8"))


def _load_postgres(url: str, recorded: Path) -> None:
    """Copy the recorded rows into PostgreSQL under the same schema, as booleans where its columns are booleans."""
    schema = (_RECORDINGS / "schema.sql").read_text(encoding="utf-8")
    schema = schema.replace("INTEGER PRIMARY KEY AUTOINCREMENT", "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY")
    fixture = (_RECORDINGS / "06_failing.sql").read_text(encoding="utf-8")
    tables = list(dict.fromkeys(re.findall(r"^INSERT INTO (\w+)", fixture, flags=re.MULTILINE)))
    with closing(sqlite3.connect(recorded)) as source, psycopg.connect(url) as target:
        target.execute(cast("LiteralString", schema))
        for table in tables:
            booleans = {
                str(row[0])
                for row in target.execute(
                    "SELECT column_name FROM information_schema.columns "
                    "WHERE table_schema = current_schema() AND table_name = %s AND data_type = 'boolean'",
                    (table,),
                ).fetchall()
            }
            cursor = source.execute(f"SELECT * FROM {table}")  # noqa: S608 - a recorded table name
            names = [column[0] for column in cursor.description]
            insert = sql.SQL("INSERT INTO {} ({}) VALUES ({})").format(
                sql.Identifier(table),
                sql.SQL(", ").join(map(sql.Identifier, names)),
                sql.SQL(", ").join(sql.Placeholder() * len(names)),
            )
            for row in cursor.fetchall():
                values = [
                    bool(value) if name in booleans and value is not None else value
                    for name, value in zip(names, row, strict=True)
                ]
                target.execute(insert, values)


@pytest.fixture(params=("sqlite", "postgres"))
def recorded_journal(
    request: pytest.FixtureRequest,
    tmp_path: Path,
) -> tuple[Callable[[], EventJournalStore], Callable[[], set[str]]]:
    """Load the recorded failing paused replies, and return an opener and the continuations' column names."""
    path = tmp_path / "journal.db"
    _load_sqlite(path)
    if request.param == "sqlite":

        def columns() -> set[str]:
            with closing(sqlite3.connect(path)) as connection:
                return {str(row[1]) for row in connection.execute("PRAGMA table_info(approval_continuations)")}

        return lambda: EventJournalStore.open_sqlite(path), columns
    url = postgres_journal_schema_url(request.getfixturevalue("postgres_journal_url"))
    _load_postgres(url, path)

    def postgres_columns() -> set[str]:
        with psycopg.connect(url) as connection:
            rows = connection.execute(
                "SELECT column_name FROM information_schema.columns "
                "WHERE table_schema = current_schema() AND table_name = 'approval_continuations'",
            ).fetchall()
        return {str(row[0]) for row in rows}

    return lambda: EventJournalStore.open_postgres(url), postgres_columns


_CONVERTED = {
    "stopped": ApprovalFailure(ApprovalFailureKind.USER_STOP),
    "sync-restart": ApprovalFailure(ApprovalFailureKind.RESTART),
    "interrupted": ApprovalFailure(ApprovalFailureKind.INTERRUPTED),
    "shutdown": ApprovalFailure(ApprovalFailureKind.SHUTDOWN),
    "errored": ApprovalFailure(
        ApprovalFailureKind.ERROR,
        "Tool approval resume failed: the model provider returned HTTP 502.",
    ),
}


async def test_each_stored_failure_reason_becomes_its_kind(
    recorded_journal: tuple[Callable[[], EventJournalStore], Callable[[], set[str]]],
) -> None:
    """Each failing paused reply keeps failing, with the kind its stored reason named and an error's text as detail."""
    open_journal, columns = recorded_journal
    assert "failure_reason" in columns()
    store = open_journal()
    try:
        approvals = store.principal(_RESPONDER).approvals
        for approval_id, failure in _CONVERTED.items():
            continuation = await approvals.approval_continuation(approval_id)
            assert continuation is not None
            assert (continuation.state, continuation.failure) == ("failing", failure)
    finally:
        await store.close()
    assert {"failure_kind", "failure_detail"} <= columns()
    assert "failure_reason" not in columns()


async def test_the_conversion_runs_once(
    recorded_journal: tuple[Callable[[], EventJournalStore], Callable[[], set[str]]],
) -> None:
    """A journal the conversion already upgraded opens unchanged."""
    open_journal, columns = recorded_journal
    await open_journal().close()
    converted = columns()
    store = open_journal()
    try:
        continuation = await store.principal(_RESPONDER).approvals.approval_continuation("errored")
        assert continuation is not None
        assert continuation.failure == _CONVERTED["errored"]
    finally:
        await store.close()
    assert columns() == converted
