def _expand_byte_order(sql: str, dialect: _Dialect) -> str:
    """Spell the byte-order pin for one backend."""
    return sql.replace(_BYTE_ORDER_MARKER, dialect.order_by_bytes)


def schema_statements(dialect: _Dialect) -> tuple[str, ...]:
    """Return every DDL statement needed to create the current schema.

    The byte-order marker is substituted here as well as in queries. An index
    whose trailing columns sort in the server's own collation cannot satisfy an
    ORDER BY that pins them to byte order -- PostgreSQL simply declines to use
    it and sorts instead. Leaving the marker unexpanded is silent on SQLite,
    whose default text collation is already byte order, so the mismatch shows up
    only on the backend that is not measured by a local query-plan test.
    """
    return tuple(
        _expand_byte_order(statement, dialect).format(
            receipt_order_column=dialect.receipt_order_column,
            ordered_text=dialect.ordered_text,
        )
        for statement in (*_TABLES, *_INDEXES)
    )


def render(sql: str, dialect: _Dialect) -> str:
    """Return SQL with parameter placeholders spelled for one backend.

    Statements are authored with ``?`` and never contain a literal string, so
    substitution cannot touch anything but a parameter marker.
    """
    if "'?" in sql or "?'" in sql:
        msg = "Event-journal SQL must not embed a literal question mark"
        raise ValueError(msg)
    # Substitution is a plain string rewrite, so a marker inside an authored
    # string literal would be rewritten as if it were an identifier. No
    # statement has one and no user value reaches here -- values are bound
    # separately by both backends -- but the rewriter cannot tell, so the
    # adjacency is rejected rather than trusted, the same way a literal
    # question mark is.
    if f"'{_BYTE_ORDER_MARKER}" in sql or f"{_BYTE_ORDER_MARKER}'" in sql:
        msg = "Event-journal SQL must not embed the byte-order marker in a literal"
        raise ValueError(msg)
    sql = sql.replace(_BYTE_ORDER_MARKER, dialect.order_by_bytes)
    if dialect.placeholder == "?":
        return sql
    return sql.replace("?", dialect.placeholder)
