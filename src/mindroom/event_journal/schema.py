"""One schema definition rendered for both durable backends.

The journal, projection, and outbox exist once as SQL. A dialect supplies only
the handful of spellings SQLite and PostgreSQL genuinely disagree about, so
neither backend can drift into its own behavior.
"""

from __future__ import annotations

from dataclasses import dataclass

_BYTE_ORDER_MARKER = "/*bytes*/"

PENDING_STATE = "pending"
SETTLED_STATE = "settled"


@dataclass(frozen=True, slots=True)
class _Dialect:
    """The spellings that differ between the two supported backends."""

    placeholder: str
    # A surrogate receipt-order key that is never reused after deletion,
    # because replay ordering and refresh tokens are both derived from it.
    receipt_order_column: str
    # Text that participates in ordering or range comparison. PostgreSQL's
    # default locale can order text differently from SQLite and from Python,
    # so any column a cursor compares is pinned to byte order explicitly.
    ordered_text: str
    # The same pin applied to an expression rather than a column declaration,
    # for columns that were already shipped unpinned and cannot be retyped
    # without rewriting the table.
    order_by_bytes: str


SQLITE_DIALECT = _Dialect(
    placeholder="?",
    receipt_order_column="INTEGER PRIMARY KEY AUTOINCREMENT",
    ordered_text="TEXT",
    # SQLite compares TEXT with BINARY unless told otherwise, which is already
    # byte order.
    order_by_bytes="",
)

POSTGRES_DIALECT = _Dialect(
    placeholder="%s",
    receipt_order_column="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ordered_text='TEXT COLLATE "C"',
    order_by_bytes=' COLLATE "C"',
)


