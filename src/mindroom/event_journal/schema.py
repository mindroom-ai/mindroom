"""One schema definition rendered for both durable backends.

The journal, projection, and outbox exist once as SQL. A dialect supplies only
the handful of spellings SQLite and PostgreSQL genuinely disagree about, so
neither backend can drift into its own behavior.
"""

from __future__ import annotations

from dataclasses import dataclass

_BYTE_ORDER_MARKER = "/*bytes*/"

PENDING_STATE = "pending"
SETTLED_STATE = "settled"


@dataclass(frozen=True, slots=True)
class SchemaDialect:
    """The spellings that differ between the two supported backends."""

    placeholder: str
    # A surrogate receipt-order key that is never reused after deletion,
    # because replay ordering and refresh tokens are both derived from it.
    receipt_order_column: str
    # Text that participates in ordering or range comparison. PostgreSQL's
    # default locale can order text differently from SQLite and from Python,
    # so any column a cursor compares is pinned to byte order explicitly.
    ordered_text: str
    # The same pin applied to an expression rather than a column declaration,
    # for columns that were already shipped unpinned and cannot be retyped
    # without rewriting the table.
    order_by_bytes: str


SQLITE_DIALECT = SchemaDialect(
    placeholder="?",
    receipt_order_column="INTEGER PRIMARY KEY AUTOINCREMENT",
    ordered_text="TEXT",
    # SQLite compares TEXT with BINARY unless told otherwise, which is already
    # byte order.
    order_by_bytes="",
)

POSTGRES_DIALECT = SchemaDialect(
    placeholder="%s",
    receipt_order_column="BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    ordered_text='TEXT COLLATE "C"',
    order_by_bytes=' COLLATE "C"',
)


OUTBOX_TABLE = """
    CREATE TABLE IF NOT EXISTS matrix_delivery_outbox (
        principal_id TEXT NOT NULL,
        delivery_id TEXT NOT NULL,
        stage TEXT NOT NULL CHECK (stage IN ('initial', 'final', 'edit')),
        event_type TEXT NOT NULL,
        room_id TEXT NOT NULL,
        membership_epoch BIGINT NOT NULL,
        thread_id TEXT NOT NULL,
        transaction_id TEXT NOT NULL,
        payload_json TEXT NOT NULL,
        -- Local semantic facts needed after acknowledgement. These are not
        -- Matrix event content and are never sent by the delivery worker.
        result_json TEXT,
        edits_event_id TEXT,
        -- A durable edit can be reserved before the INITIAL event ID exists.
        -- Its claim waits until INITIAL acknowledgement fills the target.
        edit_target_pending INTEGER NOT NULL DEFAULT 0,
        attempted INTEGER NOT NULL DEFAULT 0,
        retired INTEGER NOT NULL DEFAULT 0,
        permanent_failure_reason TEXT,
        -- The device whose transaction ID the homeserver may already hold. A
        -- transaction ID deduplicates within one device, so a row attempted by
        -- a device this process is no longer logged in as carries an ID that
        -- would be accepted as new -- and post the answer twice.
        sending_device_id TEXT,
        acknowledged_event_id TEXT,
        created_at_ns BIGINT NOT NULL,
        -- Rows that write an agent or team reply carry its identity and its
        -- place in the reply's one write sequence, so every row of one reply,
        -- across all of its spans and delivery ids, is sent in order.
        reply_id TEXT,
        span_id TEXT,
        reply_sequence BIGINT,
        -- What a reply row's acknowledgement and late edit target need, kept
        -- apart from result_json, which the outbox's other readers treat as an answer.
        reply_row_json TEXT,
        PRIMARY KEY (principal_id, delivery_id, stage)
    )
"""


# LEGACY_COMPAT: Converted approval calls whose tool name or invoking agent the old rows never stored.
# Legacy format: background_approval_calls kept no tool name or agent, so the conversion reads them from the call's card
# payload; a call whose card had already retired has no payload left, and a reply call rebuilt from a live card's
# payload has none when that payload lacked them. Selected by the approval records conversion in
# legacy_approval_records.py; every call the current release inserts stores both.
# Last legacy release: v2026.10.655; replacement: the next release stores both on every approval_calls row it writes.
# Handling: approval_calls.tool_name and approval_calls.invoking_agent stay nullable and hold NULL only in those
# converted rows. Each is decided, and nothing reads them: a paused reply's calls are read only while the reply exists,
# and those were copied from approval_continuation_calls, which stored both; a card's invoking agent is read only to
# authorize a click on an undecided detached call's live card, whose payload named it.
