#!/usr/bin/env node

const fs = require("fs");
const path = require("path");

const toolsMetadataPath = path.join(__dirname, "../../src/mindroom/tools_metadata.json");
const outputPath = path.join(__dirname, "../src/components/Integrations/iconMapping.tsx");

/** Claim the icons named with `prefix` and then an uppercase letter or a digit, so lucide's `GitBranch` stays lucide's. */
function prefixed(prefix) {
  const name = new RegExp(`^${prefix}[A-Z0-9]`);
  return icon => name.test(icon);
}

// Each icon library, in the order the file imports and maps it, with the test for the icons it provides. An icon goes to
// the first library whose test it passes, so lucide-react, last, takes every icon no other library claims.
const LIBRARIES = [
  ["react-icons/fa", prefixed("Fa")],
  ["react-icons/fi", prefixed("Fi")],
  ["react-icons/si", prefixed("Si")],
  ["react-icons/gi", prefixed("Gi")],
  ["react-icons/tb", prefixed("Tb")],
  ["react-icons/vsc", prefixed("Vsc")],
  ["react-icons/wi", prefixed("Wi")],
  ["./awsIcons", prefixed("Aws")],
  ["lucide-react", () => true],
];

const HEADER = `// THIS FILE IS AUTO-GENERATED - DO NOT EDIT MANUALLY
// Generated by scripts/generate-icon-imports.cjs from tools_metadata.json

import React, { createElement, lazy, Suspense } from "react";
`;

const MAP_OPENING = `
// Map of all icons we use
export const iconMap: Record<
  string,
  React.ComponentType<{ className?: string }>
> = {
`;

const FOOTER = `};

const LazyLucideIcon = lazy(() => import("./LucideIcon"));

/** Resolve explicit icons consistently, loading the full Lucide catalog only when needed. */
export function getIconForTool(
  iconName: string | null,
  iconColor?: string | null,
  fallbackIcon: React.ComponentType<{ className?: string }> = Globe,
): React.ReactNode {
  const className = \`h-5 w-5 \${iconColor || ""}\`.trim();
  const fallback = createElement(fallbackIcon, { className });
  if (!iconName) return fallback;

  if (Object.prototype.hasOwnProperty.call(iconMap, iconName)) {
    return createElement(iconMap[iconName], { className });
  }

  return createElement(
    Suspense,
    { fallback },
    createElement(LazyLucideIcon, { name: iconName, className, fallback }),
  );
}

// Export specific lucide icons that might be needed elsewhere
export {
  Calculator,
  Folder,
  Terminal,
  Code,
  Book,
  Globe,
  Search,
  Newspaper,
  TrendingUp,
  FileText,
  Database,
  Mail,
  Film,
  VolumeX,
  Volume2,
} from "lucide-react";
`;

/** Return every icon the tools declare, as `[library, icons]` pairs in `LIBRARIES` order. */
function groupIcons(toolsMetadata) {
  const iconNames = new Set();
  for (const tool of toolsMetadata.tools) {
    if (tool.icon) {
      iconNames.add(tool.icon);
    }
  }

  // The fallback must be available even when no tool declares it.
  iconNames.add("Globe");

  const groups = LIBRARIES.map(([library]) => [library, []]);
  for (const icon of iconNames) {
    groups[LIBRARIES.findIndex(([, provides]) => provides(icon))][1].push(icon);
  }
  return groups;
}

function iconImport(library, icons) {
  if (icons.length === 1) {
    return `import { ${icons[0]} } from "${library}";\n`;
  }

  return `import {\n  ${icons.join(",\n  ")},\n} from "${library}";\n`;
}

/** Render iconMapping.tsx for these icon groups. */
function renderIconMapping(groups) {
  const used = groups.filter(([, icons]) => icons.length > 0);
  const imports = used.map(([library, icons]) => iconImport(library, icons)).join("");
  const entries = used.flatMap(([, icons]) => icons.map(icon => `  ${icon},\n`)).join("");
  return HEADER + imports + MAP_OPENING + entries + FOOTER;
}

module.exports = { groupIcons, renderIconMapping };

if (require.main === module) {
  const groups = groupIcons(JSON.parse(fs.readFileSync(toolsMetadataPath, "utf8")));
  fs.writeFileSync(outputPath, renderIconMapping(groups), "utf8");
  console.log(`✅ Generated icon imports for ${groups.flatMap(([, icons]) => icons).length} unique icons`);
  for (const [library, icons] of groups) {
    console.log(`   - ${icons.length} from ${library}`);
  }
  console.log(`📁 Output: ${outputPath}`);
}
